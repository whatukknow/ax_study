-- =====================================================================
-- Todo 앱 테이블 + RLS 정책 (Supabase 대시보드 > SQL Editor 에 붙여넣고 Run)
-- =====================================================================

-- 1) todos 테이블 생성
--    id          : 자동 증가 정수 기본키 (identity)
--    created_at  : 생성 시각, 기본값 now()
--    title       : 할 일 내용 (빈 값 금지)
--    is_completed: 완료 여부, 기본값 false
--    user_id     : 작성자 uuid. 기본값 auth.uid() → insert 할 때 앱에서 따로 넣지 않아도
--                  "지금 로그인한 사용자"의 id 가 자동으로 들어간다.
create table if not exists public.todos (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  title text not null,
  is_completed boolean not null default false,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade
);

-- 2) RLS(Row Level Security) 활성화
--    켜는 순간 "정책으로 허용한 행"만 읽고/쓰기 가능해진다. (정책이 없으면 아무것도 안 보임)
alter table public.todos enable row level security;

-- 3) 정책 4개: 로그인한 사용자(authenticated)는 "자기 user_id 와 같은 행"만 다룰 수 있다.
--    (select auth.uid()) 처럼 select 로 감싸면 행마다 함수를 다시 호출하지 않아 성능이 좋다.

-- 3-1) 조회: 내 할 일만 보인다
create policy "Users can view their own todos"
on public.todos for select
to authenticated
using ( (select auth.uid()) = user_id );

-- 3-2) 추가: user_id 가 나 자신인 행만 넣을 수 있다
create policy "Users can insert their own todos"
on public.todos for insert
to authenticated
with check ( (select auth.uid()) = user_id );

-- 3-3) 수정: 내 행만 수정할 수 있고, 수정 후에도 user_id 가 나여야 한다
create policy "Users can update their own todos"
on public.todos for update
to authenticated
using ( (select auth.uid()) = user_id )
with check ( (select auth.uid()) = user_id );

-- 3-4) 삭제: 내 행만 삭제할 수 있다
create policy "Users can delete their own todos"
on public.todos for delete
to authenticated
using ( (select auth.uid()) = user_id );

-- 4) (선택) 목록 조회 속도를 위한 인덱스: user_id 로 거르고 created_at 으로 정렬하므로
create index if not exists todos_user_id_created_at_idx
  on public.todos (user_id, created_at desc);
